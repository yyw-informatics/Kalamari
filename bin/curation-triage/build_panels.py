#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
build_panels.py -- Tier 2: build the committed sub-species ANI panels.

The 13 Kalamari units that carry a *synthetic* taxid (Listeria monocytogenes
lineages I-IV, Clostridium botulinum groups I-II, seven Salmonella enterica
subspecies) are **metadata-blind**: NCBI knows nothing about a lineage that only
Kalamari defines, so Tier 1's whole signal -- NCBI's own verdict on the assembly --
cannot say anything about them.  The four Salmonella units with real subspecies
taxids sit in the same position for the same practical reason.  For all of these
the only available signal is sequence: place the genome against a small panel of
lineage references and see where it lands.

**What a panel contains (decided 2026-08-04): Kalamari's own sibling units.**  A
panel for unit X lists the other Kalamari units in X's confounded group -- real
accessions already curated and version-checked in ``src/chromosomes.tsv``.  Two
questions become answerable offline and without inventing reference accessions
we cannot verify:

  * **distinctness** -- is X still ANI-distinct from its siblings, or have two of
    Kalamari's lineage references drifted into being the same genome (>= the
    ``derep`` threshold)?  A curated lineage set whose members are not distinct is
    a real curation defect, and nothing else in the tool can see it.
  * **placement** -- when a new deposit is a candidate for one of these lineages,
    which Kalamari lineage is it actually nearest to?

Each file keeps a commented ``external:`` block.  Curated outside references
(type strains, published lineage exemplars) belong there, but only after a
network pass has verified each accession -- an unverified accession in a curation
tool is worse than no accession, so none are guessed here.

Regenerate (the test suite asserts the committed files match this output):

    python3 bin/curation-triage/build_panels.py --write
"""

from __future__ import annotations

import argparse
import csv
import os
import sys
from collections import OrderedDict
from typing import Dict, List

REPO_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SRC = os.path.join(REPO_ROOT, "src", "curation-triage")
DEFAULT_POLICY = os.path.join(SRC, "taxon_policy.tsv")
DEFAULT_PANEL_DIR = os.path.join(SRC, "panels")

PANEL_COLUMNS = ["accession", "lineage_label", "unit_id", "role"]

# Only regime B gets a panel: there ANI/sketch genuinely resolves the units and the
# residual problem is the label.  Regime A (Shigella/E. coli, anthracis/cereus,
# pestis/pseudotuberculosis) is exactly the case where genome-wide similarity is the
# wrong ruler, so those units are resolved by markers (markers.py) and a panel would
# be misleading rather than merely useless.
PANEL_REGIME = "B"


def _panel_header(unit_id: str, label: str, group: str, n: int) -> List[str]:
    return [
        "# ANI panel for Kalamari unit %s" % unit_id,
        "# lineage: %s" % label,
        "# confounded group: %s" % group,
        "#",
        "# Generated by bin/curation-triage/build_panels.py from taxon_policy.tsv.",
        "# Do not hand-edit the rows: regenerate with --write.",
        "#",
        "# Members are the %d other Kalamari unit(s) in this group (real, curated" % n,
        "# accessions).  Tier 2 skanis this unit against every member and reports",
        "# (a) the nearest member and the ANI margin to the runner-up, and",
        "# (b) any member closer than the derep threshold, which would mean two",
        "#     Kalamari lineage references are no longer distinct genomes.",
        "#",
        "# external: curated outside lineage references go below this line, one per",
        "# external: row, ONLY after a network pass has verified each accession.",
        "#",
    ]


def load_panel_groups(policy_path: str) -> "OrderedDict[str, List[dict]]":
    """Group the regime-B confounded units by their confounded-group note."""
    groups: "OrderedDict[str, List[dict]]" = OrderedDict()
    with open(policy_path, newline="", encoding="utf-8") as fh:
        for r in csv.DictReader(fh, delimiter="\t"):
            if r.get("eligibility") != "eligible":
                continue
            if (r.get("regime") or "").strip() != PANEL_REGIME:
                continue
            note = (r.get("note") or "").strip()
            group = note.split("confounded:", 1)[1].strip() if "confounded:" in note else note
            groups.setdefault(group, []).append(r)
    for members in groups.values():
        members.sort(key=lambda r: r["unit_id"])
    return groups


def render_panel(unit: dict, siblings: List[dict], group: str) -> str:
    """The .acclist text for one unit (header comments + one row per sibling)."""
    lines = _panel_header(unit["unit_id"], unit["scientificName"], group, len(siblings))
    lines.append("\t".join(PANEL_COLUMNS))
    for s in siblings:
        lines.append("\t".join([s["parent_assembly"], s["scientificName"], s["unit_id"],
                                "sibling"]))
    return "\n".join(lines) + "\n"


def build_panels(policy_path: str) -> "OrderedDict[str, str]":
    """Map ``<kalamari_taxid>.acclist`` -> file text, for every regime-B unit."""
    out: "OrderedDict[str, str]" = OrderedDict()
    for group, members in load_panel_groups(policy_path).items():
        for unit in members:
            siblings = [m for m in members if m["unit_id"] != unit["unit_id"]]
            out["%s.acclist" % unit["kalamari_taxid"]] = render_panel(unit, siblings, group)
    return OrderedDict(sorted(out.items()))


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description="Build the Tier 2 sub-species ANI panels.")
    p.add_argument("--policy", default=DEFAULT_POLICY)
    p.add_argument("--panel-dir", default=DEFAULT_PANEL_DIR)
    p.add_argument("--write", action="store_true",
                   help="Write the panels (default: report what would change).")
    args = p.parse_args(argv)

    panels = build_panels(args.policy)
    changed: List[str] = []
    for name, text in panels.items():
        path = os.path.join(args.panel_dir, name)
        current = None
        if os.path.exists(path):
            with open(path, encoding="utf-8") as fh:
                current = fh.read()
        if current != text:
            changed.append(name)
            if args.write:
                os.makedirs(args.panel_dir, exist_ok=True)
                with open(path, "w", encoding="utf-8") as fh:
                    fh.write(text)
    print("%d panel(s) for %d unit(s); %d %s" % (
        len(panels), len(panels), len(changed),
        "written" if args.write else "would change"), file=sys.stderr)
    for name in changed:
        print("  %s %s" % ("wrote" if args.write else "differs:", name), file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
